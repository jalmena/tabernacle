package songfs

import (
	"errors"
	"fmt"
	"path"
	"strings"
	"unicode"
	"unicode/utf8"
)

// Ext is the only file extension Tabernacle reads or writes.
const Ext = ".song"

// maxDepth bounds how deep the collection may nest. Two levels (Artist/Title)
// is the documented layout; the rest is slack for people who organise by genre
// or by band and album. The limit exists so a pathological tree cannot make a
// scan run away.
const maxDepth = 8

// maxSegmentBytes caps one generated path segment. 100 bytes leaves room for a
// collision suffix inside the 255-byte limit that ext4, APFS and NTFS all
// share, even when every character is a three-byte rune.
const maxSegmentBytes = 100

// maxNameBytes and maxPathBytes are the limits every filesystem Tabernacle is
// likely to meet agrees on. Checking them here means an over-long path is
// refused with a clear reason rather than surfacing as a platform-specific
// ENAMETOOLONG from somewhere deeper.
const (
	maxNameBytes = 255
	maxPathBytes = 1024
)

// ErrNotLocal reports a relative path that does not stay inside the collection.
//
// Callers should treat this as a bug or an attack rather than a typo: paths
// reaching this package are either generated by it or come from the index, so
// there is nothing legitimate to sanitise. Anything user-typed is turned into a
// path by RelPathFor instead.
var ErrNotLocal = errors.New("path is not inside the collection")

// CheckRel validates a relative path used to address a song.
//
// Confinement itself is enforced by os.Root at every syscall; this is the
// cheap, explicit layer in front of it, so that a bad path is rejected with a
// clear reason instead of a syscall error, and so the rules are stated in one
// testable place.
func CheckRel(rel string) error {
	switch {
	case rel == "":
		return fmt.Errorf("empty path: %w", ErrNotLocal)
	case strings.ContainsRune(rel, 0):
		return fmt.Errorf("path contains a NUL byte: %w", ErrNotLocal)
	case !utf8.ValidString(rel):
		return fmt.Errorf("path is not valid UTF-8: %w", ErrNotLocal)
	case strings.ContainsRune(rel, '\\'):
		// A backslash is a path separator on Windows and a legal filename
		// character on Unix, so accepting it would mean the same string naming
		// two different files depending on the host.
		return fmt.Errorf("path contains a backslash: %w", ErrNotLocal)
	case strings.HasPrefix(rel, "/"):
		return fmt.Errorf("path is absolute: %w", ErrNotLocal)
	case len(rel) > 1 && rel[1] == ':':
		return fmt.Errorf("path has a drive letter: %w", ErrNotLocal)
	case len(rel) > maxPathBytes:
		return fmt.Errorf("path is longer than %d bytes: %w", maxPathBytes, ErrNotLocal)
	}

	segs := strings.Split(rel, "/")
	if len(segs) > maxDepth {
		return fmt.Errorf("path is more than %d levels deep: %w", maxDepth, ErrNotLocal)
	}
	for _, s := range segs {
		switch s {
		case "":
			return fmt.Errorf("path has an empty segment: %w", ErrNotLocal)
		case ".", "..":
			return fmt.Errorf("path contains %q: %w", s, ErrNotLocal)
		}
		if len(s) > maxNameBytes {
			return fmt.Errorf("path segment is longer than %d bytes: %w", maxNameBytes, ErrNotLocal)
		}
		if strings.TrimSpace(s) != s {
			return fmt.Errorf("path segment %q is padded with whitespace: %w", s, ErrNotLocal)
		}
		for _, r := range s {
			if r < 0x20 || r == 0x7f {
				return fmt.Errorf("path segment %q contains a control character: %w", s, ErrNotLocal)
			}
		}
	}

	// path.Clean is the last word: if cleaning changes anything, the original
	// was not already canonical and should not be trusted.
	if path.Clean(rel) != rel {
		return fmt.Errorf("path %q is not in canonical form: %w", rel, ErrNotLocal)
	}
	if !strings.EqualFold(path.Ext(rel), Ext) {
		return fmt.Errorf("path %q does not end in %s: %w", rel, Ext, ErrNotLocal)
	}
	if base := path.Base(rel); base == Ext {
		return fmt.Errorf("path %q has no name before %s: %w", rel, Ext, ErrNotLocal)
	}
	return nil
}

// windowsReserved are device names that cannot be used as filenames on Windows,
// with or without an extension.
//
// Tabernacle runs on Linux, but a collection is a directory people copy to a
// laptop or a USB stick as a backup, and a file called "aux.song" is one that
// silently fails to restore.
var windowsReserved = map[string]bool{
	"con": true, "prn": true, "aux": true, "nul": true,
	"com0": true, "com1": true, "com2": true, "com3": true, "com4": true,
	"com5": true, "com6": true, "com7": true, "com8": true, "com9": true,
	"lpt0": true, "lpt1": true, "lpt2": true, "lpt3": true, "lpt4": true,
	"lpt5": true, "lpt6": true, "lpt7": true, "lpt8": true, "lpt9": true,
}

// SanitizeSegment turns free text into one safe path segment.
//
// Accents and spaces survive: the collection is meant to be browsed in a file
// manager, and "Ain't No Sunshine.song" is the right filename for that song.
// Slugification belongs in URLs, not on disk.
//
// The result is never empty, never a dotfile, never a Windows device name, and
// never longer than maxSegmentBytes.
func SanitizeSegment(s string) string {
	var b strings.Builder
	b.Grow(len(s))
	for _, r := range s {
		switch {
		case r == utf8.RuneError:
			b.WriteByte('-') // invalid input bytes become a separator, not garbage
		case r < 0x20, r == 0x7f:
			b.WriteByte(' ') // a newline in a title should not glue two words together
		case strings.ContainsRune(`/\:*?"<>|`, r):
			b.WriteByte('-')
		case unicode.IsSpace(r):
			b.WriteByte(' ')
		default:
			b.WriteRune(r)
		}
	}

	out := fit(strings.Trim(collapse(b.String()), " .-"))
	if out == "" {
		return "untitled"
	}

	// Defusing a device name comes after the length has been settled, because
	// shortening can produce one: "con." followed by two hundred characters is
	// not a device name, and its first hundred bytes are. Prefixing then puts the
	// segment one byte over, so it is fitted a second time — which cannot loop,
	// since a name beginning with an underscore is never reserved.
	//
	// The comparison ignores any extension, since "nul.txt" is reserved too.
	if windowsReserved[strings.ToLower(strings.TrimSuffix(out, path.Ext(out)))] {
		out = fit("_" + out)
	}
	return out
}

// fit caps a segment at maxSegmentBytes, cutting on a rune boundary and trimming
// the separators a cut can leave exposed at the end.
func fit(s string) string {
	if len(s) <= maxSegmentBytes {
		return s
	}
	cut := maxSegmentBytes
	for cut > 0 && !utf8.RuneStart(s[cut]) {
		cut--
	}
	return strings.Trim(s[:cut], " .-")
}

// collapse squeezes runs of spaces and runs of hyphens down to one each.
func collapse(s string) string {
	var b strings.Builder
	b.Grow(len(s))
	var prev rune
	for _, r := range s {
		if (r == ' ' || r == '-') && r == prev {
			continue
		}
		b.WriteRune(r)
		prev = r
	}
	return b.String()
}

// RelPathFor derives the path a song should live at from its own metadata.
//
// User input never becomes a path directly: a filename is always generated
// here, which is what keeps every write inside the collection by construction
// rather than by filtering. A song with no artist goes in the top level.
func RelPathFor(artist, title string) string {
	file := SanitizeSegment(title) + Ext
	if a := SanitizeSegment(artist); strings.TrimSpace(artist) != "" {
		return a + "/" + file
	}
	return file
}

// withSuffix inserts a disambiguating suffix before the extension:
// "Amazing Grace.song" with n=2 becomes "Amazing Grace (2).song".
func withSuffix(rel string, n int) string {
	dir, file := path.Split(rel)
	ext := path.Ext(file)
	base := strings.TrimSuffix(file, ext)
	return dir + fmt.Sprintf("%s (%d)%s", base, n, ext)
}
